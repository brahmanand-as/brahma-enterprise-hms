CREATE TABLE permissions(code VARCHAR(80) PRIMARY KEY,label VARCHAR(160) NOT NULL);
CREATE TABLE enterprise_roles(name VARCHAR(40) PRIMARY KEY,label VARCHAR(100) NOT NULL,system_role BOOLEAN NOT NULL DEFAULT FALSE);
CREATE TABLE role_permissions(role_name VARCHAR(40) NOT NULL,permission_code VARCHAR(80) NOT NULL,PRIMARY KEY(role_name,permission_code),FOREIGN KEY(role_name) REFERENCES enterprise_roles(name),FOREIGN KEY(permission_code) REFERENCES permissions(code));
ALTER TABLE staff_accounts ADD token_version INT NOT NULL DEFAULT 0;
CREATE TABLE care_teams(patient_id BIGINT NOT NULL,username VARCHAR(80) NOT NULL,PRIMARY KEY(patient_id,username),FOREIGN KEY(patient_id) REFERENCES patients(id),FOREIGN KEY(username) REFERENCES staff_accounts(username));
CREATE TABLE notifications(id BIGINT PRIMARY KEY AUTO_INCREMENT,username VARCHAR(80) NOT NULL,subject VARCHAR(180) NOT NULL,message VARCHAR(1000) NOT NULL,is_read BOOLEAN NOT NULL DEFAULT FALSE,created_at DATETIME DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE issued_documents(id BIGINT PRIMARY KEY AUTO_INCREMENT,patient_id BIGINT NOT NULL,document_type VARCHAR(30) NOT NULL,reference_id BIGINT NOT NULL,verification_token CHAR(36) NOT NULL UNIQUE,content_json LONGTEXT NOT NULL,issued_by VARCHAR(80) NOT NULL,issued_at DATETIME DEFAULT CURRENT_TIMESTAMP,UNIQUE KEY uk_issued(document_type,reference_id),FOREIGN KEY(patient_id) REFERENCES patients(id));
CREATE TABLE helpdesk_messages(id BIGINT PRIMARY KEY AUTO_INCREMENT,ticket_id BIGINT NOT NULL,username VARCHAR(80) NOT NULL,message VARCHAR(2000) NOT NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(ticket_id) REFERENCES helpdesk_tickets(id));
ALTER TABLE helpdesk_tickets ADD department VARCHAR(100),ADD due_at DATETIME;
ALTER TABLE reschedule_requests ADD resolved_by VARCHAR(80),ADD resolved_at DATETIME;
